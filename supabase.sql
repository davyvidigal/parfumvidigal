-- Cria tabelas, permissões e bucket público para fotos dos produtos.

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  price numeric(12,2) not null default 0 check (price >= 0),
  category text not null check (category in ('masculino','feminino','unissex')),
  image text,
  stock integer not null default 0 check (stock >= 0),
  description text default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.charges (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  phone text not null,
  amount numeric(12,2) not null check (amount > 0),
  description text default '',
  items jsonb not null default '[]'::jsonb,
  paid boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.product_interest (
  product_id bigint primary key references public.products(id) on delete cascade,
  views bigint not null default 0,
  searches bigint not null default 0,
  clicks bigint not null default 0
);

create or replace function public.is_store_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_store_admin() from public;
grant execute on function public.is_store_admin() to authenticated;

alter table public.admin_users enable row level security;
alter table public.products enable row level security;
alter table public.charges enable row level security;
alter table public.product_interest enable row level security;

drop policy if exists "Admins can read admin list" on public.admin_users;
create policy "Admins can read admin list" on public.admin_users
for select to authenticated using (public.is_store_admin());

drop policy if exists "Public can view active products" on public.products;
create policy "Public can view active products" on public.products
for select to anon, authenticated using (active = true or public.is_store_admin());

drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products
for all to authenticated using (public.is_store_admin())
with check (public.is_store_admin());

drop policy if exists "Admins manage charges" on public.charges;
create policy "Admins manage charges" on public.charges
for all to authenticated using (public.is_store_admin())
with check (public.is_store_admin());

drop policy if exists "Public can read product interest" on public.product_interest;
create policy "Public can read product interest" on public.product_interest
for select to anon, authenticated using (public.is_store_admin());

drop policy if exists "Public can increment interest" on public.product_interest;
create policy "Public can increment interest" on public.product_interest
for insert to anon, authenticated with check (true);

drop policy if exists "Public can update interest" on public.product_interest;
create policy "Public can update interest" on public.product_interest
for update to anon, authenticated using (true) with check (true);

-- Bucket de imagens. Upload/alteração/exclusão somente por administrador autenticado.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880,
allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Public can view product images" on storage.objects;
create policy "Public can view product images" on storage.objects
for select to anon, authenticated using (bucket_id = 'product-images');

drop policy if exists "Admins upload product images" on storage.objects;
create policy "Admins upload product images" on storage.objects
for insert to authenticated with check (bucket_id = 'product-images' and public.is_store_admin());

drop policy if exists "Admins update product images" on storage.objects;
create policy "Admins update product images" on storage.objects
for update to authenticated using (bucket_id = 'product-images' and public.is_store_admin())
with check (bucket_id = 'product-images' and public.is_store_admin());

drop policy if exists "Admins delete product images" on storage.objects;
create policy "Admins delete product images" on storage.objects
for delete to authenticated using (bucket_id = 'product-images' and public.is_store_admin());

